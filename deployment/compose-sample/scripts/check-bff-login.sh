#!/bin/bash
# Log in through the compose sample's BFF exactly as a browser does, and fail unless it works.
#
# THIS IS A REAL LOGIN FLOW, NOT A SMOKE TEST. It drives the whole authorization-code round trip —
# gateway, pushed authorization request, the identity provider's login form, the credential POST, the
# gateway callback, the session-protected route — with one cookie jar, following every redirect itself,
# and asserts what each leg answers. A green run means a browser user can sign in to the running sample
# and reach the upstream through the session the gateway holds. Each step proves one thing:
#
#   1. NEGATIVE CONTROL. An API request for {path} with no session must answer 401. If the route were
#      public, the demo body would be served without any login and the assertion in step 5 would hold
#      whatever the login did — this step is what keeps step 5 from being vacuous.
#   2. LOGIN START. A browser navigation (Accept: text/html) to the same {path} must answer 302 to an
#      authorization endpoint whose query carries client_id and request_uri: the gateway pushed its
#      authorization request over the back channel (PAR) before redirecting, so the browser carries
#      only a reference to it.
#   3. LOGIN FORM. Following that redirect — plus the one extra redirect Keycloak answers a pushed
#      request with, into its own login-actions flow — must reach a page with a password form. The
#      form's action is read out of the page, and the credentials are posted to it; the identity
#      provider must answer with a redirect, which is how it reports an accepted login.
#   4. CALLBACK. The redirect chain is followed back through the gateway's callback, where the gateway
#      exchanges the code (signing its client assertion and DPoP proof) and creates the session, to the
#      {path} the login started from.
#   5. SESSION. The final answer must be 200 carrying the demo upstream's marker, "service":"demo-api",
#      and the cookie jar must hold the gateway's __Host- session cookie under its configured name.
#
# What it never does: skip TLS verification (every request verifies against the sample's generated
# certificate with --cacert — never -k), wait without bound (every request carries --max-time), or
# print a cookie value, a token, a code or a password. On a failure it prints the failing step, the
# HTTP status and the response headers, with Set-Cookie values and every URL query redacted, and
# exits non-zero.
#
# Nothing here is variant- or IdP-host-specific: every URL after the first comes from a Location
# header or a form action the gateway or the identity provider emitted. So the base sample, the
# plain-HTTP variant (`start-sample.sh --plain-http`, where nginx answers the TLS handshake on the same
# URL) and any later variant that moves the identity provider reuse this script unchanged, and
# start-sample.sh stays the one bring-up. Run it against a stack start-sample.sh reported ready.
#
# Invoked by the deployment module's opt-in `compose-sample` Maven profile at integration-test, and
# directly by an operator following doc/user/compose-sample.adoc. Both paths are the same path.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SAMPLE_DIR="$(dirname "${SCRIPT_DIR}")"

# The defaults address the sample as start-sample.sh brings it up, and log in as the realm's one user
# (docker/keycloak/sample-realm.json). SAMPLE CREDENTIALS — the same ones the operator guide names.
BASE_URL="https://localhost:8443"
START_PATH="/app"
USERNAME="sample-user"
PASSWORD="CHANGE-ME-BEFORE-PRODUCTION"
# gateway.yaml's oidc.session.cookie_name.
SESSION_COOKIE="__Host-sample-session"
# The sample's self-signed certificate, generated by docker/certificates/generate-certificates.sh. It
# is served by the gateway (or the plain-HTTP variant's terminator) AND by Keycloak, so it is the one
# trust anchor every leg of the flow verifies against.
CA_CERT="${SAMPLE_DIR}/docker/certificates/localhost.crt"

CONNECT_TIMEOUT=10
REQUEST_TIMEOUT=30
# How many redirects step 4 follows from the credential response: the hop to the callback and the
# callback's own redirect to {path}, with one to spare. A chain longer than this is a loop.
MAX_RETURN_HOPS=4

usage() {
    echo "Usage: ${0##*/} [--base-url URL] [--path PATH] [--username NAME] [--password PASSWORD]"
    echo "                [--session-cookie NAME]"
    echo ""
    echo "  --base-url URL         The gateway's browser-facing origin (default ${BASE_URL})."
    echo "  --path PATH            A session-protected route to log in for (default ${START_PATH})."
    echo "  --username NAME        The realm user to sign in as (default ${USERNAME})."
    echo "  --password PASSWORD    That user's password (default: the sample realm's)."
    echo "  --session-cookie NAME  The gateway's session cookie name (default ${SESSION_COOKIE})."
}

while (( $# > 0 )); do
    case "$1" in
        --base-url|--path|--username|--password|--session-cookie)
            if (( $# < 2 )); then
                echo "❌ $1 needs a value"
                echo ""
                usage
                exit 2
            fi
            case "$1" in
                --base-url) BASE_URL="$2" ;;
                --path) START_PATH="$2" ;;
                --username) USERNAME="$2" ;;
                --password) PASSWORD="$2" ;;
                --session-cookie) SESSION_COOKIE="$2" ;;
            esac
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "❌ Unknown option: $1"
            echo ""
            usage
            exit 2
            ;;
    esac
done

BASE_URL="${BASE_URL%/}"
if [[ "$BASE_URL" != https://* && "$BASE_URL" != http://* ]]; then
    echo "❌ --base-url must be an absolute http(s) URL (got ${BASE_URL})"
    exit 2
fi
if [[ "$START_PATH" != /* ]]; then
    echo "❌ --path must start with / (got ${START_PATH})"
    exit 2
fi

if [[ ! -f "${CA_CERT}" ]]; then
    echo "❌ ${CA_CERT} is missing. It is generated, never committed — run"
    echo "   ./docker/certificates/generate-certificates.sh and bring the sample up with"
    echo "   ./scripts/start-sample.sh first."
    exit 1
fi

for tool in curl python3; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "❌ ${tool} is required and was not found on PATH"
        exit 1
    fi
done

# Everything this run writes — the cookie jar, the credential files, each response — lives in one
# private directory, removed on EVERY exit path. mktemp -d creates it mode 700.
WORK_DIR="$(mktemp -d)"
cleanup() {
    rm -rf "${WORK_DIR}"
}
trap cleanup EXIT

COOKIE_JAR="${WORK_DIR}/cookies.txt"
HEADERS="${WORK_DIR}/headers.txt"
BODY="${WORK_DIR}/body.txt"
# The credentials reach curl through files, never through its argument list, so they do not show up
# in a process listing while the POST is in flight. printf '%s' — no trailing newline in the value.
USERNAME_FILE="${WORK_DIR}/username"
PASSWORD_FILE="${WORK_DIR}/password"
printf '%s' "${USERNAME}" > "${USERNAME_FILE}"
printf '%s' "${PASSWORD}" > "${PASSWORD_FILE}"

# The small parsing jobs a shell does badly: headers, URLs, HTML. One program, one subcommand per job.
#
# Read with `read -d ''` rather than captured with "$(cat <<'PY' ...)": the bash 3.2 macOS ships
# scans a command substitution for quotes before it sees the heredoc, so an apostrophe in the program
# breaks the parse there. read returns 1 when it reaches the end without a NUL, hence the `|| true`.
IFS= read -r -d '' PY_HELPER <<'PY' || true
import sys
from html.parser import HTMLParser
from urllib.parse import parse_qs, urljoin, urlsplit


def read_headers(path):
    # The header block of the one response curl wrote (redirects are never followed by curl here).
    with open(path, encoding="iso-8859-1") as handle:
        lines = [line.rstrip("\r\n") for line in handle]
    return [line.split(":", 1) for line in lines[1:] if ":" in line]


def without_query(url):
    parts = urlsplit(url)
    rendered = "%s://%s%s" % (parts.scheme, parts.netloc, parts.path) if parts.scheme else parts.path
    return rendered + ("?<query redacted>" if parts.query else "")


class PasswordForm(HTMLParser):
    def __init__(self):
        super().__init__()
        self.forms = []
        self.current = None

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        if tag == "form":
            self.current = {"action": values.get("action") or "",
                            "method": (values.get("method") or "get").lower(),
                            "password": False}
            self.forms.append(self.current)
        elif tag == "input" and self.current is not None \
                and (values.get("type") or "").lower() == "password":
            self.current["password"] = True

    def handle_endtag(self, tag):
        if tag == "form":
            self.current = None


command, args = sys.argv[1], sys.argv[2:]

if command == "header":
    # header FILE NAME -> the value of the last NAME header, or nothing.
    wanted = args[1].lower()
    found = [value.strip() for name, value in read_headers(args[0]) if name.strip().lower() == wanted]
    sys.stdout.write(found[-1] if found else "")
elif command == "redact-headers":
    # redact-headers FILE -> the header block with every cookie value and URL query removed.
    with open(args[0], encoding="iso-8859-1") as handle:
        lines = [line.rstrip("\r\n") for line in handle]
    for line in lines:
        if not line:
            continue
        name, sep, value = line.partition(":")
        lowered = name.strip().lower()
        if sep and lowered == "set-cookie":
            print("%s: %s=<redacted>" % (name, value.strip().split("=", 1)[0]))
        elif sep and lowered in ("location", "content-location"):
            print("%s: %s" % (name, without_query(value.strip())))
        else:
            print(line)
elif command == "resolve":
    # resolve BASE REF -> REF made absolute against BASE.
    sys.stdout.write(urljoin(args[0], args[1]))
elif command == "redact-url":
    sys.stdout.write(without_query(args[0]))
elif command == "origin":
    parts = urlsplit(args[0])
    sys.stdout.write("%s://%s" % (parts.scheme, parts.netloc.lower()))
elif command == "path":
    sys.stdout.write(urlsplit(args[0]).path)
elif command == "query-has":
    # query-has URL KEY... -> exit 0 when every KEY carries a non-empty value in URL's query.
    query = parse_qs(urlsplit(args[0]).query)
    sys.exit(0 if all(query.get(key, [""])[0] for key in args[1:]) else 1)
elif command == "form-action":
    # form-action FILE PAGE_URL -> the absolute action of the page's POST form holding a password field.
    parser = PasswordForm()
    with open(args[0], encoding="utf-8", errors="replace") as handle:
        parser.feed(handle.read())
    actions = [form["action"] for form in parser.forms
               if form["password"] and form["method"] == "post" and form["action"]]
    if not actions:
        sys.exit(1)
    sys.stdout.write(urljoin(args[1], actions[0]))
elif command == "jar-has":
    # jar-has JAR NAME -> exit 0 when curl's cookie jar holds a cookie named NAME. Names only; a value
    # is never read out of the jar.
    with open(args[0], encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if line.startswith("#HttpOnly_"):
                line = line[len("#HttpOnly_"):]
            elif line.startswith("#"):
                continue
            fields = line.rstrip("\r\n").split("\t")
            if len(fields) >= 7 and fields[5] == args[1]:
                sys.exit(0)
    sys.exit(1)
else:
    sys.exit("unknown helper command %r" % command)
PY

helper() {
    python3 -c "${PY_HELPER}" "$@"
}

CURRENT_STEP=""
STATUS=""

step() {
    CURRENT_STEP="$1"
    echo "⏳ ${CURRENT_STEP}"
}

# Reports the failing step with the status and the redacted headers of the last response, and exits.
fail() {
    echo ""
    echo "❌ ${CURRENT_STEP}"
    echo "   $1"
    if [[ -s "${HEADERS}" ]]; then
        echo "----- response headers (cookie values and URL queries redacted) -----"
        helper redact-headers "${HEADERS}" || true
        echo "-----"
    fi
    exit 1
}

# request URL [curl arguments...] — one request, never following a redirect, with the status left in
# STATUS and the response in HEADERS and BODY. The cookie jar is read and written by the callers that
# pass -b/-c, so step 1's negative control can run without it.
request() {
    local url="$1"
    shift
    : > "${HEADERS}"
    : > "${BODY}"
    if ! STATUS="$(curl --silent --show-error \
            --cacert "${CA_CERT}" \
            --connect-timeout "${CONNECT_TIMEOUT}" --max-time "${REQUEST_TIMEOUT}" \
            --dump-header "${HEADERS}" --output "${BODY}" --write-out '%{http_code}' \
            "$@" "${url}")"; then
        fail "the request to $(helper redact-url "${url}") failed before an HTTP answer arrived (see curl's message above)"
    fi
}

TARGET_URL="${BASE_URL}${START_PATH}"
echo "🔐 Logging in through the BFF at $(helper redact-url "${TARGET_URL}") as ${USERNAME}"

# ---- 1. Negative control ------------------------------------------------------------------------
step "Step 1/5: an API request without a session must be refused"
request "${TARGET_URL}" --header "Accept: application/json"
if [[ "${STATUS}" != "401" ]]; then
    fail "expected 401 for a session-less API request, got ${STATUS} — a route that does not demand a session would make the whole check vacuous"
fi

# ---- 2. Login start -----------------------------------------------------------------------------
step "Step 2/5: a browser navigation must start a pushed login"
request "${TARGET_URL}" --header "Accept: text/html" \
    --cookie "${COOKIE_JAR}" --cookie-jar "${COOKIE_JAR}"
if [[ "${STATUS}" != "302" ]]; then
    fail "expected 302 into the identity provider, got ${STATUS}"
fi
AUTHORIZATION_URL="$(helper header "${HEADERS}" location)"
if [[ "${AUTHORIZATION_URL}" != https://* ]]; then
    fail "expected an absolute https authorization URL, got '$(helper redact-url "${AUTHORIZATION_URL}")'"
fi
if ! helper query-has "${AUTHORIZATION_URL}" client_id request_uri; then
    fail "the authorization URL carries no client_id and request_uri — the request was not pushed"
fi

# ---- 3. Login form and credentials --------------------------------------------------------------
step "Step 3/5: the identity provider must serve its login form and accept the credentials"
LOGIN_PAGE_URL="${AUTHORIZATION_URL}"
request "${LOGIN_PAGE_URL}" --header "Accept: text/html" \
    --cookie "${COOKIE_JAR}" --cookie-jar "${COOKIE_JAR}"
if [[ "${STATUS}" == "302" || "${STATUS}" == "303" ]]; then
    # Keycloak answers a pushed request with one redirect into its own authentication flow. Exactly
    # one, on its own origin, into login-actions: a refused authorization request is ALSO a redirect —
    # to the client's redirect URI with an error — and that one must fail here, not be followed.
    NEXT_URL="$(helper resolve "${LOGIN_PAGE_URL}" "$(helper header "${HEADERS}" location)")"
    if [[ "$(helper origin "${NEXT_URL}")" != "$(helper origin "${LOGIN_PAGE_URL}")" \
            || "$(helper path "${NEXT_URL}")" != */login-actions/* ]]; then
        fail "the identity provider redirected the authorization request to $(helper redact-url "${NEXT_URL}") instead of its own login flow — the request was refused"
    fi
    LOGIN_PAGE_URL="${NEXT_URL}"
    request "${LOGIN_PAGE_URL}" --header "Accept: text/html" \
        --cookie "${COOKIE_JAR}" --cookie-jar "${COOKIE_JAR}"
fi
if [[ "${STATUS}" != "200" ]]; then
    fail "expected the login page (200) after at most one redirect, got ${STATUS}"
fi
if ! FORM_ACTION="$(helper form-action "${BODY}" "${LOGIN_PAGE_URL}")"; then
    fail "the login page carries no POST form with a password field"
fi

request "${FORM_ACTION}" --header "Accept: text/html" \
    --cookie "${COOKIE_JAR}" --cookie-jar "${COOKIE_JAR}" \
    --data-urlencode "username@${USERNAME_FILE}" --data-urlencode "password@${PASSWORD_FILE}"
if [[ "${STATUS}" != "302" && "${STATUS}" != "303" ]]; then
    fail "expected a redirect accepting the login, got ${STATUS} — a page instead of a redirect means the credentials were refused"
fi

# ---- 4. Back through the callback ---------------------------------------------------------------
step "Step 4/5: the redirects must lead back through the gateway callback to ${START_PATH}"
NEXT_URL="$(helper resolve "${FORM_ACTION}" "$(helper header "${HEADERS}" location)")"
if [[ "$(helper origin "${NEXT_URL}")" != "$(helper origin "${TARGET_URL}")" ]]; then
    fail "the identity provider sent the browser to $(helper redact-url "${NEXT_URL}"), not back to the gateway"
fi
CALLBACK_SEEN=false
for ((hop = 1; hop <= MAX_RETURN_HOPS; hop++)); do
    CURRENT_URL="${NEXT_URL}"
    request "${CURRENT_URL}" --header "Accept: text/html" \
        --cookie "${COOKIE_JAR}" --cookie-jar "${COOKIE_JAR}"
    if [[ "${STATUS}" != 3?? ]]; then
        break
    fi
    # The first hop is the callback: it must complete the login with a redirect, which is what this
    # flag records. An error answer there leaves the loop with that status instead.
    CALLBACK_SEEN=true
    NEXT_URL="$(helper resolve "${CURRENT_URL}" "$(helper header "${HEADERS}" location)")"
    if (( hop == MAX_RETURN_HOPS )); then
        fail "still redirecting after ${MAX_RETURN_HOPS} hops — a redirect loop, not a completed login"
    fi
done
if [[ "${CALLBACK_SEEN}" != "true" ]]; then
    fail "the gateway callback answered ${STATUS} instead of completing the login with a redirect"
fi
if [[ "$(helper path "${CURRENT_URL}")" != "$(helper path "${TARGET_URL}")" ]]; then
    fail "the login returned to $(helper redact-url "${CURRENT_URL}"), not to ${START_PATH}"
fi

# ---- 5. The session -----------------------------------------------------------------------------
step "Step 5/5: the session must reach the upstream"
if [[ "${STATUS}" != "200" ]]; then
    fail "expected 200 from ${START_PATH} with the session, got ${STATUS}"
fi
if ! grep -qF '"service":"demo-api"' "${BODY}"; then
    fail "the 200 does not carry the demo upstream's \"service\":\"demo-api\" marker"
fi
if ! helper jar-has "${COOKIE_JAR}" "${SESSION_COOKIE}"; then
    fail "the cookie jar holds no ${SESSION_COOKIE} session cookie"
fi

echo ""
echo "✅ Logged in through the BFF: ${START_PATH} answered 200 from demo-api over the ${SESSION_COOKIE} session."
